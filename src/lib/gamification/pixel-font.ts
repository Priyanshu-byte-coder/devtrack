export const GLYPH_WIDTH = 5;
export const GLYPH_HEIGHT = 7;
/** Advance per character, in font pixels: the glyph plus one column of space. */
export const GLYPH_ADVANCE = 6;

/** Lowercase letters map to capitals; "v" is reserved for the down arrow. */
function glyphFor(ch: string): string[] {
  if (ch === "v") return GLYPHS.v;
  return GLYPHS[ch.toUpperCase()] ?? GLYPHS["?"];
}

/** Width in screen pixels of `text` at `scale` screen pixels per font pixel. */
export function pixelTextWidth(text: string, scale: number): number {
  if (!text) return 0;
  return (text.length * GLYPH_ADVANCE - 1) * scale;
}

/**
 * SVG path data for `text` with its top-left at (x, y). Each lit font pixel
 * becomes a `scale`-sized square; runs of lit pixels in a row are merged into
 * one rectangle to keep the path short.
 */
export function pixelTextPath(
  text: string,
  x: number,
  y: number,
  scale: number
): string {
  const parts: string[] = [];
  [...text].forEach((ch, i) => {
    const glyph = glyphFor(ch);
    const ox = x + i * GLYPH_ADVANCE * scale;
    glyph.forEach((row, ry) => {
      let col = 0;
      while (col < row.length) {
        if (row[col] !== "1") {
          col++;
          continue;
        }
        let end = col;
        while (end < row.length && row[end] === "1") end++;
        parts.push(
          `M${ox + col * scale} ${y + ry * scale}h${(end - col) * scale}v${scale}h${-(end - col) * scale}z`
        );
        col = end;
      }
    });
  });
  return parts.join("");
}
