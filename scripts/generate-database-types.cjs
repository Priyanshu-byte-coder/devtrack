// Generate contracts from the canonical schema in disposable PostgreSQL.
const fs = require("node:fs");
const { createTestDatabase } = require("./check-database.cjs");
const map = (type) =>
  ({
    jsonb: "Json",
    json: "Json",
    boolean: "boolean",
    integer: "number",
    bigint: "number",
    numeric: "number",
    real: "number",
    "double precision": "number",
    ARRAY: "string[]",
  })[type] || "string";
async function main() {
  const db = await createTestDatabase();
  try {
    await db.exec(fs.readFileSync("supabase/schema.sql", "utf8"));
    const { rows } = await db.query(
      `SELECT table_name,column_name,data_type,is_nullable,column_default,is_generated,is_identity FROM information_schema.columns WHERE table_schema='public' ORDER BY table_name,ordinal_position`
    );
    const { rows: fk } =
      await db.query(`SELECT con.conname, child.relname AS child, parent.relname AS parent,
    array_agg(ca.attname ORDER BY cols.ordinality) AS columns, array_agg(pa.attname ORDER BY cols.ordinality) AS referenced
    FROM pg_constraint con JOIN pg_class child ON con.conrelid=child.oid JOIN pg_class parent ON con.confrelid=parent.oid
    JOIN pg_namespace ns ON child.relnamespace=ns.oid
    CROSS JOIN LATERAL unnest(con.conkey,con.confkey) WITH ORDINALITY AS cols(child_key,parent_key,ordinality)
    JOIN pg_attribute ca ON ca.attrelid=child.oid AND ca.attnum=cols.child_key JOIN pg_attribute pa ON pa.attrelid=parent.oid AND pa.attnum=cols.parent_key
    WHERE con.contype='f' AND ns.nspname='public' GROUP BY con.conname,child.relname,parent.relname`);
    const { rows: uniqueKeys } =
      await db.query(`SELECT child.relname AS table_name, array_agg(a.attname ORDER BY a.attname) AS columns
      FROM pg_constraint con JOIN pg_class child ON con.conrelid=child.oid JOIN pg_namespace ns ON child.relnamespace=ns.oid
      CROSS JOIN LATERAL unnest(con.conkey) AS key(attnum) JOIN pg_attribute a ON a.attrelid=child.oid AND a.attnum=key.attnum
      WHERE con.contype IN ('p','u') AND ns.nspname='public' GROUP BY con.conname,child.relname`);
    const grouped = Object.groupBy(rows, (row) => row.table_name);
    const renderTable = (name) => {
      const fields = grouped[name];
      const render = (kind) =>
        fields
          .map((c) => {
            const generated =
              c.is_generated === "ALWAYS" || c.is_identity === "YES";
            const optional =
              kind === "Update" ||
              (kind === "Insert" &&
                (generated ||
                  c.column_default !== null ||
                  c.is_nullable === "YES"));
            const type =
              kind !== "Row" && generated
                ? "never"
                : map(c.data_type) + (c.is_nullable === "YES" ? " | null" : "");
            return `          ${c.column_name}${optional ? "?" : ""}: ${type};`;
          })
          .join("\n");
      const relationships = fk
        .filter((f) => f.child === name)
        .map((f) => ({
          foreignKeyName: f.conname,
          columns: f.columns,
          isOneToOne: uniqueKeys.some(
            (key) =>
              key.table_name === name &&
              [...key.columns].sort().join(",") ===
                [...f.columns].sort().join(",")
          ),
          referencedRelation: f.parent,
          referencedColumns: f.referenced,
        }));
      return `      ${name}: {\n        Row: {\n${render("Row")}\n        };\n        Insert: {\n${render("Insert")}\n        };\n        Update: {\n${render("Update")}\n        };\n        Relationships: ${JSON.stringify(relationships)};\n      };`;
    };
    const tables = Object.keys(grouped)
      .filter((name) => name !== "linked_accounts")
      .map(renderTable)
      .join("\n");
    const result = `// Generated by scripts/generate-database-types.cjs from supabase/schema.sql.\nexport type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];\nexport type Database = {\n  public: {\n    Tables: {\n${tables}\n    };\n    Views: {\n${renderTable("linked_accounts")}\n    };\n    Functions: {\n      delete_app_user: { Args: { p_user_id: string; p_github_id: string }; Returns: boolean };\n      rollover_goals: { Args: { p_user_id: string; p_now: string }; Returns: undefined };\n      claim_cron_job: { Args: { p_name: string; p_token: string }; Returns: Json };\n      batch_upsert_sessions: { Args: { sessions: Json }; Returns: undefined };\n      respond_to_room_invitation: { Args: { p_invitation_id: string; p_github_id: string; p_accept: boolean }; Returns: Json };\n    };\n    Enums: Record<never, never>;\n    CompositeTypes: Record<never, never>;\n  };\n};\n`;
    if (process.argv.includes("--check")) {
      if (fs.readFileSync("src/types/supabase.ts", "utf8") !== result)
        throw new Error(
          "Database types differ from canonical schema. Run npm run supabase:generate-types."
        );
    } else fs.writeFileSync("src/types/supabase.ts", result);
    console.log("Database type contracts verified.");
  } finally {
    await db.close();
  }
}
main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
